function R = buildFrame( ...
    progression,...
    rasi,...
    lasi)

Y = normalizeVector(progression);

Zraw = rasi - lasi;

Zraw = ...
    Zraw - ...
    dot(Zraw,Y)*Y;

Z = normalizeVector(Zraw);

X = normalizeVector( ...
    cross(Y,Z));

Z = normalizeVector( ...
    cross(X,Y));

R = [ ...
    X(:) ...
    Y(:) ...
    Z(:)];

end